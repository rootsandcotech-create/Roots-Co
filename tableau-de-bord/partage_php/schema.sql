-- Tableau de bord ROOTS, version partagée (MySQL). install.php crée ces tables automatiquement.
CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  nom VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  mdp_hash VARCHAR(255) NOT NULL,
  role VARCHAR(12) NOT NULL DEFAULT 'equipe',   -- admin, equipe, lecture
  actif INTEGER NOT NULL DEFAULT 1,
  cree_le VARCHAR(25) NOT NULL,
  derniere_connexion VARCHAR(25) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS statuts (
  pub_id VARCHAR(40) NOT NULL PRIMARY KEY, statut VARCHAR(40) NOT NULL, par_nom VARCHAR(120) NOT NULL, maj_le VARCHAR(25) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS historique (
  id INTEGER PRIMARY KEY AUTO_INCREMENT, pub_id VARCHAR(40) NOT NULL, titre VARCHAR(300) NOT NULL, canal VARCHAR(30) NOT NULL,
  ancien VARCHAR(40) NOT NULL, nouveau VARCHAR(40) NOT NULL, par_nom VARCHAR(120) NOT NULL, le VARCHAR(25) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS controles (
  pub_id VARCHAR(40) NOT NULL, cle VARCHAR(60) NOT NULL, ok INTEGER NOT NULL DEFAULT 0, par_nom VARCHAR(120) NOT NULL, maj_le VARCHAR(25) NOT NULL,
  PRIMARY KEY (pub_id, cle)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS tentatives (
  id INTEGER PRIMARY KEY AUTO_INCREMENT, ip VARCHAR(45) NOT NULL, le INTEGER NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
